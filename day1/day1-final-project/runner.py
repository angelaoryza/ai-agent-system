"""
The small runner behind main.py (Day 1 and Day 2). Given: you do not edit this file.

check(module, name, fn) runs one function's check and prints one line:
    ✅  it works            ⏳  not written yet (the placeholder still raises NotImplementedError)
    ❌  it ran but is wrong (the message says what to fix)
"""

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent          # runner.py sits in the project folder
results = []          # (module, name, state)


def check(module, name, fn):
    """Run fn(). It may return a short detail for the ✅ line, or raise AssertionError to say what is wrong."""
    try:
        detail, state, icon = fn() or "", "pass", "✅"
    except NotImplementedError:
        detail, state, icon = "not written yet", "todo", "⏳"
    except AssertionError as e:
        detail, state, icon = str(e), "fail", "❌"
    except Exception as e:                        # a crash in the student's code: show it, keep going
        detail, state, icon = f"{type(e).__name__}: {e}", "fail", "❌"
    if state == "fail" and "TODO" in detail:           # failed only because an earlier function is still a placeholder
        detail, state, icon = "waiting for an earlier function: " + detail, "todo", "⏳"
    print(f"  {icon} {name}{': ' + detail if detail else ''}")
    results.append((module, name, state))
    return state == "pass"


def skip(module, name, reason):
    print(f"  ⏭  {name}: {reason}")
    results.append((module, name, "todo"))


def summary():
    print("\n── Summary " + "─" * 60)
    for module in dict.fromkeys(m for m, _, _ in results):
        states = [s for m, _, s in results if m == module]
        print(f"  {module}: {states.count('pass')}/{len(states)} checks pass"
              + (f", {states.count('todo')} not written yet" if "todo" in states else "")
              + (f", {states.count('fail')} to fix" if "fail" in states else ""))
    done = all(s == "pass" for _, _, s in results)
    print("\n🎉 Everything passes!" if done else "\nKeep going: fix the ❌ lines first, then write the ⏳ ones.")
    return 0 if done else 1


def run(stages, extras=None):
    """stages: {"m2": (title, function), ...} run in order. extras: {"demo": (title, function)} run only when named.
    Usage:  python main.py            every module
            python main.py m3 m4      only these
            python main.py demo       an extra, by name"""
    os.chdir(ROOT)                                        # the data paths are relative to this folder
    extras = extras or {}
    wanted = sys.argv[1:] or list(stages)
    unknown = [w for w in wanted if w not in stages and w not in extras]
    if unknown:
        sys.exit(f"Unknown: {unknown}. Choose from {list(stages) + list(extras)}")
    for name in wanted:
        title, fn = stages.get(name) or extras[name]
        print(f"\n━━ {name.upper()}: {title} " + "━" * max(3, 60 - len(title)))
        fn()
    if any(w in stages for w in wanted):
        sys.exit(summary())
