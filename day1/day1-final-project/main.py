# ── Module 2: the data layer ───────────────────────────────────────────────────

def check_m2():
    def financials():
        result = m2.get_quarterly_financials("ASII")
        assert result and result["quarter_end"] == "2026-09-30", "The latest quarter should end on 2026-09-30"
        assert {"revenue", "earnings", "total_debt", "total_equity", "cash", "is_cached"} <= set(result)
        return f"revenue {result['revenue']:,} in the quarter to {result['quarter_end']}"

    def fallback():
        with mock.patch.object(m2, "BASE_URL", "https://api.sectors.app.invalid/v2"):      # pretend Sectors is down
            saved = m2.get_quarterly_financials("ASII")
        assert saved and saved["is_cached"] is True, "When Sectors is down, use the saved copy and set is_cached"
        return "Sectors down: the saved copy is used and marked"

    def account():
        table, notes = m2.load_account(CLIENT["account_file"])
        assert notes == {"bad_rows": 1, "duplicates": 1}, f"Expected 1 bad row and 1 duplicate date, got {notes}"
        assert len(table) == 64 and table["date"].is_monotonic_increasing, "64 clean rows, sorted by date"
        folder = tempfile.mkdtemp()
        pd.read_csv(CLIENT["account_file"]).drop(columns="facility_limit").to_csv(f"{folder}/broken.csv", index=False)
        try:
            m2.load_account(f"{folder}/broken.csv")
        except ValueError as e:
            assert "facility_limit" in str(e), "Name the missing column in the error"
        else:
            raise AssertionError("A missing column should raise ValueError")
        return f"{len(table)} rows, {notes}"

    def pdf():
        pages = m2.read_pdf_text("data/call_reports/ASII/2026-10-21_call_report.pdf")
        assert pages and len(pages) == 2 and all(p["has_text"] for p in pages), "The 21 Oct report has 2 pages of text"
        assert "IDR 3 trillion" in pages[0]["text"], "The text of page 1 should mention the capex plan"
        return f"{len(pages)} pages"

    def call_reports():
        folder = tempfile.mkdtemp()
        shutil.copytree(CLIENT["call_report_folder"], f"{folder}/reports")
        shutil.copy(f"{folder}/reports/2026-07-15_call_report.pdf", f"{folder}/reports/meeting_notes.pdf")
        reports, skipped = m2.load_call_reports(f"{folder}/reports")
        assert [r["meeting_date"] for r in reports] == ["2026-10-21", "2026-09-10", "2026-07-15"], "Newest first"
        assert skipped == ["meeting_notes.pdf"], "A file without a date in its name is skipped"
        return f"{len(reports)} reports, skipped {skipped}"

    def news():
        result = m2.scrape_news(CLIENT["news_url"], WEEK_END)
        assert [a["date"] for a in result["articles"]] == ["2026-10-30", "2026-10-29", "2026-10-28"], "3 articles this week"
        assert result["articles"][0]["link"].startswith("http"), "Links should be absolute"
        offline = m2.scrape_news("http://localhost:9/astra.html", WEEK_END)
        assert offline["is_cached"] and len(offline["articles"]) == 3, "When the page fails, use the saved copy"
        return f"{len(result['articles'])} articles this week (saved copy works too)"

    def given():                       # the Given functions, which use yours
        data = m2.collect_client_data(CLIENT, WEEK_END)
        assert data["problems"] == [], f"collect_client_data reported problems: {data['problems']}"
        assert os.path.isdir("data/news") and os.listdir("data/news"), "The news should be saved in data/news (Module 5 reads it)"
        assert m2.get_company_overview("ASII")["name"] and m2.get_daily_prices("ASII", "2026-10-19", WEEK_END)
        return "all four sources collected, news saved in data/news"

    check("M2", "get_quarterly_financials", financials)
    check("M2", "get_quarterly_financials (fallback)", fallback)
    check("M2", "load_account", account)
    check("M2", "read_pdf_text", pdf)
    check("M2", "load_call_reports", call_reports)
    check("M2", "scrape_news", news)
    check("M2", "collect_client_data (given, uses all of the above)", given)


# ── Module 3: automation ───────────────────────────────────────────────────────

def check_m3():
    def section():
        missing = m3.build_account_section(None)
        assert missing and missing["status"] == "missing" and missing["text"].startswith("Not available"), "Say what is missing"
        table, _ = m2.load_account(CLIENT["account_file"])
        result = m3.build_account_section(m2.summarize_account_week(table, WEEK_END))
        for expected in ["+18.0%", "72.0%", "60.0%", "+12.0 points", "IDR 247.8B"]:
            assert expected in result["text"], f"The account table should show {expected}"
        return "inflow +18.0%, facility usage 60.0% -> 72.0%"

    def given_sections():
        prices = [{"date": "2026-10-23", "close": 100}, {"date": "2026-10-30", "close": 110}]
        assert m3.weekly_price_change(prices)["change"] == 10.0, "weekly_price_change should give +10.0%"
        assert m3.build_news_section(None)["status"] == "missing" and m3.build_call_report_section([])["status"] == "missing"
        return "market, call report and news sections handle a missing source"

    def report_with_missing_source():
        broken = {**CLIENT, "account_file": "data/account/XXXX.csv"}
        path = m3.run_weekly_report(broken, WEEK_END)
        assert path and os.path.exists(path), "The run should still save a report when one source fails"
        with open(path, encoding="utf-8") as f:
            assert "## Account activity (missing)" in f.read(), "The report should say the account section is missing"
        with open("output/run_log.txt", encoding="utf-8") as f:
            assert " partial: " in f.readlines()[-1], "The log line should say partial"
        return "a missing source did not stop the run, and the report says so"

    def report():                      # last, so the saved sections (read by Module 4) are the complete ones
        path = m3.run_weekly_report(CLIENT, WEEK_END)
        assert path and os.path.exists(path) and os.path.exists(path.replace(".md", ".json")), "Save the report (.md) and its sections (.json)"
        with open(path, encoding="utf-8") as f:
            text = f.read()
        assert "## Account activity" in text and "## News this week" in text, "The report should have all four sections"
        return path

    def scheduler():
        sched, job = m3.start_scheduler()
        nxt = job.next_run_time
        sched.shutdown()
        assert (nxt.weekday(), nxt.hour, nxt.minute) == (0, 7, 0), f"Next run should be a Monday at 07:00, got {nxt}"
        return f"next run {nxt}"

    check("M3", "build_account_section", section)
    check("M3", "weekly_price_change and the other sections (given)", given_sections)
    check("M3", "run_weekly_report (a source missing)", report_with_missing_source)
    check("M3", "run_weekly_report (all sources)", report)
    check("M3", "start_scheduler", scheduler)


# ── Module 4: the first LLM calls ──────────────────────────────────────────────

def check_m4():
    path = f"output/reports/{CLIENT['ticker']}_{WEEK_END}.json"
    if not os.path.exists(path):
        return skip("M4", "all checks", "run `python main.py m3` first: it saves the sections Module 4 reads")
    with open(path, encoding="utf-8") as f:
        saved = json.load(f)
    latest = saved["data"]["call_reports"][0]
    text = "\n".join(page["text"] for page in latest["pages"])
    ctx = {}

    def prompt():
        messages = m4.build_brief_prompt(saved["sections"])
        assert messages and messages[0] == ("system", m4.RULES), "The first message is the system prompt with the rules"
        assert "<sections>" in messages[1][1] and "Facility usage" in messages[1][1], "Put the code sections between <sections> tags"

    def form():
        assert set(m4.CallReportPoints.model_fields) == {"meeting_date", "client_plans", "client_requests", "follow_ups"}, "CallReportPoints fields"
        ctx["points"], problem = m4.call_with_form(m4.CallReportPoints, m4.CALL_PROMPT.invoke({"report": text}))
        assert ctx["points"], problem
        assert ctx["points"].meeting_date == "2026-10-21" and ctx["points"].follow_ups, "The form should hold the 21 Oct meeting and its follow-ups"
        return f"{ctx['points'].meeting_date}, follow-ups due {[f.due_date for f in ctx['points'].follow_ups]}"

    def checker():
        invented = m4.CallReportPoints(meeting_date="2026-10-21", client_plans=[m4.Point(point="x", evidence="plans to sell the company")],
                                       client_requests=[], follow_ups=[])
        assert m4.check_call_report(invented, text), "An invented evidence phrase must be reported"
        assert "points" in ctx, "(needs the form from the check above)"
        assert m4.check_call_report(ctx["points"], text) == [], f"The model's form should pass: {m4.check_call_report(ctx['points'], text)}"
        return "invented evidence caught, the model's form passes"

    def pipeline():                    # the Given jobs: news summary, brief, and the checks that guard them
        sections = m4.add_llm_sections({k: dict(v) for k, v in saved["sections"].items()}, saved["data"])
        assert list(sections)[0] == "brief" and sections["brief"]["status"] == "ok", f"The brief should pass its checks: {sections['brief']['text'][:120]}"
        return sections["brief"]["text"].split("\n")[0]

    check("M4", "build_brief_prompt", prompt)
    check("M4", "CallReportPoints (1 model call)", form)
    check("M4", "check_call_report", checker)
    check("M4", "add_llm_sections (given: news, brief and their checks; 3 model calls)", pipeline)


# ── Module 5: RAG ──────────────────────────────────────────────────────────────

def check_m5():
    if not os.path.isdir("data/news") or not os.listdir("data/news"):
        return skip("M5", "all checks", "run `python main.py m2` first: it saves the news that Module 5 searches")
    ctx = {}

    def docs():
        reports, _ = m2.load_call_reports(CLIENT["call_report_folder"])
        pages = m5.load_call_report_docs(reports)
        assert pages and len(pages) == 4, "3 call reports with 1 + 1 + 2 pages of text: 4 documents"
        assert pages[0].metadata == {"type": "call_report", "date": "2026-10-21", "page": 1, "file": "2026-10-21_call_report.pdf"}, \
            f"Wrong metadata: {pages[0].metadata}"
        return f"{len(pages)} pages"

    def search():
        m5.refresh_store()             # given: news + your call report documents -> chunks -> index
        news = m5.retrieve("electric vehicle battery plant", only_type="news")
        assert news and all(d.metadata["type"] == "news" for d in news), "only_type='news' keeps news only"
        dates = [d.metadata["date"] for d in m5.retrieve("facility limit", k=4)]
        assert dates == sorted(dates, reverse=True), "Results should be newest first"
        return f"{len(news)} news chunks; dates newest first {dates}"

    def ask():
        answer, results = m5.ask_documents("When is the next meeting with the client?", only_type="call_report")
        assert results and answer.covered and answer.cited, "The call reports answer this: covered, with citations"
        assert "December" in answer.answer, "The 21 Oct report says early December 2026"
        return answer.answer[:100] + "..."

    check("M5", "load_call_report_docs", docs)
    check("M5", "refresh_store (given) + retrieve", search)
    check("M5", "ask_documents (1 model call)", ask)


# ── The whole Day 1 pipeline ───────────────────────────────────────────────────

def demo():
    """collect (M2) -> sections (M3) -> LLM sections and brief (M4) -> index and ask (M5)."""
    data = m2.collect_client_data(CLIENT, WEEK_END)
    sections = {"account": m3.build_account_section(data.get("account")),
                "market": m3.build_market_section(data.get("market")),
                "call_reports": m3.build_call_report_section(data.get("call_reports")),
                "news": m3.build_news_section(data.get("news"))}
    sections = m4.add_llm_sections(sections, data)
    path = m3.save_report(m3.render_report(CLIENT, WEEK_END, sections, data["problems"]), CLIENT, WEEK_END)
    print(f"\n📄 Report saved: {path}")
    m5.refresh_store()
    for question in ["What did the client ask us for in the last meeting?", "What does the news say about the battery plant?"]:
        answer, _ = m5.ask_documents(question)
        print(f"\n❓ {question}\n💬 {answer.answer}")


if __name__ == "__main__":
    run({"m2": ("the data layer", check_m2), "m3": ("automation", check_m3),
         "m4": ("the first LLM calls", check_m4), "m5": ("RAG", check_m5)},
        extras={"demo": ("the whole Day 1 pipeline", demo)})
